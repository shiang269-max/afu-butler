/**
 * =========================================================
 * Family Members
 * =========================================================
 *
 * 管理家庭成員的永久身份資料。
 *
 * 這裡只處理：
 *
 * - LINE User ID
 * - 正式家庭身份
 * - 日常稱呼
 * - 不隨 Style 改變的別名
 * - 家庭角色
 * - 人格與互動資料
 *
 * =========================================================
 *
 * 注意：
 *
 * 宮廷、海盜、西方貴族、太空艦隊等
 * 「風格專屬稱呼」不應寫在這裡。
 *
 * 例如：
 *
 * - 主上
 * - 皇上
 * - 娘娘
 * - 老佛爺
 * - 太子
 * - 辰王
 *
 * 這些應由各 Style 自己管理。
 *
 * 這個檔案代表的是：
 *
 * 「這個人是誰」
 *
 * 而不是：
 *
 * 「目前要怎麼稱呼這個人」
 *
 * =========================================================
 */


export interface FamilyMember {

  /**
   * =========================================================
   * 正式家庭身份
   * =========================================================
   *
   * 用於系統辨認。
   *
   * 例如：
   *
   * - 你本人
   * - 妻子
   * - 大兒子
   * - 小兒子
   */

  identity: string;


  /**
   * =========================================================
   * 日常主要稱呼
   * =========================================================
   *
   * 家庭平常最常使用的基本稱呼。
   *
   * AI 應優先理解這些稱呼。
   */

  primaryNames: string[];


  /**
   * =========================================================
   * Mention 主要稱呼
   * =========================================================
   *
   * 現有家庭目標 / LINE Mention 流程使用。
   *
   * 原則上與 primaryNames 第一順位一致。
   */

  mentionName: string;


  /**
   * =========================================================
   * 其他固定可理解稱呼
   * =========================================================
   *
   * 用於辨認同一家庭成員的：
   *
   * - 家庭日常稱呼
   * - 固定暱稱
   * - 身份別名
   *
   * 不放入任何 Style 專屬稱呼。
   *
   * 例如：
   *
   * 宮廷 Style：
   * - 主上
   * - 老佛爺
   * - 太子
   *
   * 海盜 Style：
   * - 船長
   * - 女王
   * - 大副
   *
   * 這些都應該由 Style 系統管理。
   */

  aliases: string[];


  /**
   * =========================================================
   * 家庭角色
   * =========================================================
   */

  role: string;


  /**
   * =========================================================
   * 家庭權力定位
   * =========================================================
   */

  authority: string;


  /**
   * =========================================================
   * 個性描述
   * =========================================================
   */

  personality: string;


  /**
   * =========================================================
   * 互動方式
   * =========================================================
   *
   * 這裡描述與該家庭成員互動時的基本原則。
   *
   * Style 可以改變語氣與表演方式，
   * 但不應改變家庭成員的核心個性。
   */

  interaction: string;

}


