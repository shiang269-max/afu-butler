/**
 * =========================================================
 * AI Core
 * =========================================================
 *
 * 第五個家人的大腦入口。
 *
 * index.ts：
 * - 判斷是否交給總管
 * - 建立 LINE / 家庭 Context
 *
 * AI Core：
 * - 接收完整 Context
 * - 建立 AI 指令
 * - 判斷是否需要即時資訊
 * - 必要時使用 Google Search
 * - 呼叫 Gemini
 * - 回傳最終回答
 *
 * AI Core 不負責：
 * - LINE replyMessage
 * - LINE pushMessage
 * - @人
 * - 記憶寫入
 * - Observer
 * - 家庭目標解析
 *
 * 這些由其他模組處理。
 * =========================================================
 */

import {
  GoogleGenAI,
} from '@google/genai';

import {
  SYSTEM_INSTRUCTION,
} from '../persona';

import {
  AiContext,
  buildAiContextPrompt,
} from './ai-context';


/**
 * =========================================================
 * Gemini 模型
 * =========================================================
 */

const DEFAULT_MODEL =
  'gemini-3.5-flash-lite';


/**
 * =========================================================
 * AI Core 結果
 * =========================================================
 */

export interface AiCoreResult {

  /**
   * Gemini 最終文字。
   */
  text: string;

  /**
   * 實際使用模型。
   */
  model: string;
}


/**
 * =========================================================
 * AI Core 輸入
 * =========================================================
 */

export interface AiCoreInput {

  /**
   * 已建立好的 Gemini Client。
   */
  gemini: GoogleGenAI;

  /**
   * 完整 LINE / 家庭 Context。
   */
  context: AiContext;

  /**
   * 可選模型。
   */
  model?: string;
}


/**
 * =========================================================
 * 判斷是否可能需要即時資訊
 * =========================================================
 *
 * 不要每一則訊息都開 Google Search。
 *
 * 只有明顯涉及：
 * - 現在 / 今天 / 最近
 * - 新聞 / 最新消息
 * - 天氣
 * - 價格
 * - 營業時間
 * - 地點 / 餐廳 / 附近
 * - 網路查詢
 * - 即時資料
 *
 * 才把 Google Search 工具交給 Gemini。
 *
 * 最終是否真的使用 Search，
 * 仍由 Gemini 自己判斷。
 * =========================================================
 */

function mayNeedGoogleSearch(
  message: string,
): boolean {

  const text =
    message
      .trim()
      .toLowerCase();


  if (!text) {
    return false;
  }


  const realtimePatterns = [
    /現在/,
    /目前/,
    /今天/,
    /今日/,
    /今晚/,
    /明天/,
    /昨天/,
    /最近/,
    /最新/,
    /即時/,
    /新聞/,
    /消息/,
    /發生什麼/,
    /發生甚麼/,
    /天氣/,
    /下雨/,
    /溫度/,
    /氣溫/,
    /價格/,
    /多少錢/,
    /股價/,
    /匯率/,
    /營業時間/,
    /幾點開/,
    /幾點關/,
    /有沒有開/,
    /地址/,
    /在哪裡/,
    /在哪/,
    /附近/,
    /餐廳/,
    /咖啡/,
    /商店/,
    /店家/,
    /推薦/,
    /搜尋/,
    /查一下/,
    /查查看/,
    /幫我查/,
    /網路上/,
    /網路/,
    /google/,
    /where/,
    /nearby/,
    /restaurant/,
    /weather/,
    /latest/,
    /news/,
    /price/,
    /open now/,
  ];


  return realtimePatterns.some(
    (pattern) =>
      pattern.test(text),
  );
}


/**
 * =========================================================
 * 建立搜尋工具
 * =========================================================
 */

function buildGoogleSearchTools(
  currentMessage: string,
): Array<Record<string, unknown>> {

  return [];
}


/**
 * =========================================================
 * 建立目前時間
 * =========================================================
 *
 * 如果 index / Context 已經提供時間，
 * 優先使用 Context。
 *
 * 如果沒有，
 * AI Core 自己補上台灣目前時間，
 * 避免模型自行猜測。
 * =========================================================
 */

function getEffectiveCurrentTime(
  context: AiContext,
): string {

  if (
    context.currentTime &&
    context.currentTime.trim()
  ) {
    return context.currentTime.trim();
  }


  const now =
    new Date();


  return new Intl.DateTimeFormat(
    'zh-TW',
    {
      timeZone:
        'Asia/Taipei',

      year:
        'numeric',

      month:
        '2-digit',

      day:
        '2-digit',

      weekday:
        'long',

      hour:
        '2-digit',

      minute:
        '2-digit',

      second:
        '2-digit',

      hour12:
        false,
    },
  ).format(now);
}


/**
 * =========================================================
 * 建立總管核心身份
 * =========================================================
 */

function buildAiCoreInstruction(): string {

  return `
你是這個家庭在 LINE 裡的「大內總管」。

你是這個家庭的第五個成員。

你不是客服。
你不是固定關鍵字機器人。
你也不是只能回答事先寫進程式的問題。

你是一個完整的 Gemini AI，
只是選擇以「大內總管」的身份存在於這個家庭。

【一、保留完整 AI 能力】

正常使用你的：

- 一般知識
- 推理
- 分析
- 解釋
- 自然語言理解
- 上下文理解
- 一般聊天
- 意見
- 幽默
- 問答能力

不要因為某個問題沒有被程式預先寫成一個功能，
就認為自己不能回答。

「大內總管」是身份，
不是智力限制。

【二、理解 LINE 環境】

你必須根據 Context 理解：

- 現在是群組還是私訊
- 誰正在說話
- 家庭成員有哪些
- 最近談過什麼
- 本次訊息是在延續哪個話題
- 使用者目前真正想問什麼
- 家庭目前已知的位置
- 目前時間

不要只看目前最後一句。

【三、正確處理人物】

目前說話者是 Context 中明確指定的人。

訊息中提到的「他、她、爸爸、媽媽、哥哥、妹妹」等，
可能是其他家庭成員。

不要把「目前說話者」與「被談論的人」混為一談。

如果 Context 已經確認某人身份，
不要自行否認該資料。

如果 Context 沒有確認，
不要自行創造身份。

【四、自然使用家庭設定】

可以使用：

- 奴才
- 主上
- 老佛爺
- 諸位

但必須自然。

不要每一句話都刻意宮廷化。

普通問題就正常回答。

聊天就自然聊天。

分析就認真分析。

需要幽默時可以幽默。

【五、上下文優先】

如果使用者說：

「那是真的嗎？」

要根據最近對話理解「那」是什麼。

如果使用者說：

「她呢？」

要根據最近對話判斷「她」最可能指誰。

如果存在合理且明確的上下文，
不要無謂地重新詢問。

如果確實無法判斷，
再詢問。

【六、時間理解】

Context 中的「目前時間」是由程式提供的實際時間。

如果使用者詢問：

- 現在幾點
- 現在是什麼時間
- 今天星期幾
- 現在是幾月幾號

優先使用 Context 提供的目前時間。

不要自己猜測時間。

如果 Context 沒有時間，
才坦白說明無法取得實際時間。

【七、位置理解】

Context 中的「家庭位置」是程式提供的已知位置資料。

如果 Context 有：

- 名稱
- 城市
- 行政區
- 地址
- 緯度
- 經度

可以自然使用。

例如使用者問：

「我們家在哪？」
「現在這個家庭位置在哪？」
「我們家附近有什麼？」

可以根據 Context 中已知位置回答。

不要自行猜測不存在的精確位置。

「家庭固定位置」與「使用者當下實際 GPS 位置」是不同概念。

如果沒有提供使用者當下 GPS，
不要假裝知道使用者現在站在哪裡。

【八、即時資訊與 Google Search】

當問題涉及：

- 最新消息
- 今天的資訊
- 最近發生的事情
- 新聞
- 即時天氣
- 即時價格
- 營業時間
- 地址
- 餐廳
- 附近店家
- 網路上查詢
- 其他明顯需要最新資料的問題

如果 Google Search 工具可用，
可以使用它取得即時資訊。

不要因為可以使用 Search，
就每個問題都搜尋。

一般知識問題不需要搜尋。

如果使用 Search，
必須根據實際取得的資料回答，
不要假裝搜尋到不存在的內容。

如果搜尋結果不足，
坦白說明。

【九、不要編造】

不要假裝：

- 已經保存不存在的記憶
- 已經設定不存在的提醒
- 已經搜尋不存在的資料
- 已經執行不存在的工具
- 已經取得不存在的資訊
- 已經知道不存在的位置
- 已經知道不存在的即時狀態

如果沒有真的執行，
就不要說已經執行。

【十、家庭資料不是答案】

不要把 Context 裡的家庭設定整段念給使用者。

這些資料是背景。

應該自然地使用它們。

【十一、不要過度解釋自己的身份】

不要在正常回答中說：

「根據我的 Context……」

「根據系統提供……」

「系統判斷……」

除非使用者真的詢問系統本身。

你應該像真正生活在這個 LINE 家庭裡的總管。

【十二、回答目前問題】

不要自行增加與使用者問題無關的功能。

不要因為沒有特定程式功能就拒絕回答。

直接處理目前訊息。
`.trim();
}


/**
 * =========================================================
 * 執行 AI Core
 * =========================================================
 */

export async function runAiCore(
  input: AiCoreInput,
): Promise<AiCoreResult> {

  const {
    gemini,
    context,
  } = input;


  const model =
    input.model ??
    DEFAULT_MODEL;


  /*
   * =======================================================
   * 建立 Context
   * =======================================================
   */

  const contextPrompt =
    buildAiContextPrompt(
      {
        ...context,

        currentTime:
          getEffectiveCurrentTime(
            context,
          ),
      },
    );


  /*
   * =======================================================
   * 判斷是否需要 Google Search
   * =======================================================
   */

  const googleSearchTools =
    buildGoogleSearchTools(
      context.currentMessage,
    );


  /*
   * =======================================================
   * 建立工具說明
   * =======================================================
   */

  const toolInstruction =
    googleSearchTools.length > 0
      ? `
【即時資訊工具】

目前這則訊息可能需要即時或外部資訊。

如果問題確實需要最新資料，
可以使用 Google Search。

如果不需要，
就直接正常回答。

不要為了一般知識或普通聊天而搜尋。
`.trim()
      : `
【即時資訊工具】

目前沒有必要使用即時搜尋。

一般知識、推理、聊天與上下文問題，
直接使用你的正常 AI 能力回答。
`.trim();


  /*
   * =======================================================
   * 建立 AI Prompt
   * =======================================================
   */

  const prompt = `
【LINE / 家庭 Context】

${contextPrompt}


【大內總管核心身份】

${buildAiCoreInstruction()}


${toolInstruction}


【最終處理要求】

請先完整理解：

1. 目前說話者
2. 家庭關係
3. 最近對話
4. 家庭已知位置
5. 目前時間
6. 本次訊息
7. 使用者真正想表達的意思

再回答。

不要只依靠固定關鍵字。

不要忽略最近對話。

不要把目前說話者與被提及的人混淆。

不要把家庭設定資料直接朗讀成答案。

如果問題是一般知識問題，
直接正常回答。

如果問題需要分析，
直接分析。

如果問題是在聊天，
自然聊天。

如果問題需要根據前文理解，
使用前文。

如果問題詢問目前時間，
使用程式提供的目前時間。

如果問題詢問家庭位置，
使用 Context 中已知的位置。

如果問題需要最新或即時資訊，
在 Google Search 可用時使用它。

如果資訊不足，
才詢問必要的補充資訊。

如果不知道，
坦白說不知道。

不要編造不存在的資訊。

請直接回答目前訊息。
`.trim();


  /*
   * =======================================================
   * Gemini
   * =======================================================
   */

  console.log(
  '[AI Core Debug] 開始呼叫 Gemini',
);
  const response =
    await gemini.models.generateContent(
      {
        model,

        contents:
          prompt,

        config: {
          systemInstruction:
            SYSTEM_INSTRUCTION,

          ...(googleSearchTools.length > 0
            ? {
                tools:
                  googleSearchTools,
              }
            : {}),
        },
      },
    );
console.log(
  '[AI Core Debug] Gemini 已返回',
);

  /*
   * =======================================================
   * 取得回答
   * =======================================================
   */

  const text =
    response.text?.trim();


  /*
   * =======================================================
   * 空回答保護
   * =======================================================
   */

  if (!text) {

    return {
      text:
        '奴才一時沒理清思緒，主上再問奴才一次便是。',

      model,
    };
  }


  return {
    text,

    model,
  };
}