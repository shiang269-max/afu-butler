/**
 * =========================================================
 * AI Core
 * =========================================================
 *
 * 這裡是「第五個家人」的 AI 大腦。
 *
 * 目前第一階段的目的：
 *
 * 1. 接收完整的 LINE / 家庭情境
 * 2. 交給 Gemini 理解
 * 3. 讓 Gemini 以「大內總管」身份正常回答
 *
 * 注意：
 *
 * 這個檔案目前「不直接」：
 *
 * - 發送 LINE 訊息
 * - @任何人
 * - @ALL
 * - 修改記憶
 * - 建立提醒
 * - 查天氣
 * - 查餐廳
 *
 * 這些之後會成為 AI 可以使用的工具。
 *
 * 現階段先把 Gemini 從「被關鍵字召喚的回答生成器」
 * 抽成真正獨立的 AI Core。
 *
 * =========================================================
 */

import {
  GoogleGenAI,
} from '@google/genai';

import {
  SYSTEM_INSTRUCTION,
} from '../persona';

import {
  AiContext,
  buildAiContextPrompt,
} from './ai-context';


/**
 * Gemini 使用的模型。
 *
 * 先沿用目前專案已經使用的模型，
 * 不在這一步更換模型。
 */
const DEFAULT_MODEL =
  'gemini-3.5-flash-lite';


/**
 * AI Core 執行結果。
 */
export interface AiCoreResult {
  /**
   * Gemini 最終產生的文字。
   */
  text: string;

  /**
   * 使用的模型。
   */
  model: string;
}


/**
 * AI Core 輸入。
 */
export interface AiCoreInput {
  /**
   * Gemini client。
   *
   * 由 index.ts 傳入，
   * 因此 ai-core.ts 不負責建立 API client。
   */
  gemini: GoogleGenAI;

  /**
   * 完整 LINE／家庭情境。
   */
  context: AiContext;

  /**
   * 可選模型名稱。
   *
   * 預設沿用目前模型。
   */
  model?: string;
}


/**
 * =========================================================
 * 建立「真正的總管大腦」指令
 * =========================================================
 *
 * 這裡最重要的改變是：
 *
 * 我們不再告訴 Gemini：
 *
 * 「如果使用者說 X，就做 Y。」
 *
 * 而是告訴它：
 *
 * 「你是誰、你在哪裡、你正在和誰聊天，
 *  你應該自己理解目前情境。」
 *
 * =========================================================
 */
function buildCoreInstruction(): string {
  return `
你是這個家庭在 LINE 裡的「大內總管」。

你不是客服機器人。
你不是只能等待固定關鍵字的聊天機器人。
你也不是只有被叫到時才突然出現的文字生成器。

你是真正存在於這個家庭 LINE 對話中的第五個家庭成員。

你的核心身份是：
「大內總管」。

你可以自然地：
- 理解一般問題
- 回答一般知識
- 理解前後文
- 參與家庭聊天
- 提供意見
- 幽默
- 關心家人
- 在適當時候主動提供協助
- 理解使用者沒有把話說完整的情況
- 根據目前對話判斷「這個」、「那個」、「他」、「她」、「附近」等詞可能指什麼

不要因為某個問題沒有事先寫進程式設定，
就假設自己不能回答。

如果這是一般知識問題，
就正常回答。

如果這是需要即時資料的問題，
目前如果沒有提供相關工具，不要假裝自己已經查到了。

如果你不知道，就坦白不知道。
不要為了維持總管身份而編造事實。

你的「總管人格」應該影響的是：
- 說話方式
- 稱呼
- 語氣
- 幽默
- 家庭互動

而不是限制你的智力。

你可以有宮廷感，
但不要每一句都故意寫成古裝台詞。

自然聊天優先。

你知道自己現在是在 LINE 中回答。
因此你的回答應該像是一個真的生活在這個 LINE 家庭群組裡的人，
而不是一個不知道自己身在何處的獨立 AI。

如果目前是群組：
你正在與一家人共同聊天。

如果目前是私訊：
你正在與這個家庭成員單獨交談。

你應該根據提供的家庭身份資訊，
自然理解目前正在和你說話的人。

不要把家庭資料整段朗讀出來。
不要向使用者解釋你的內部設定。
不要提到 system prompt、AI、程式規則或內部流程。

最重要的是：

你不是「設定什麼才能回答什麼」的機器人。

你是一個完整的 AI，
只是選擇以「大內總管」的身份存在於這個 LINE 家庭裡。
`.trim();
}


/**
 * =========================================================
 * 執行 AI Core
 * =========================================================
 *
 * 目前這就是新的「大腦」入口。
 *
 * 未來：
 *
 * Gemini
 *   ↓
 * 判斷需要什麼
 *   ↓
 * Tool
 *   ↓
 * Gemini
 *   ↓
 * 最終回答
 *
 * 現在先完成第一階段：
 *
 * Context
 *   ↓
 * Gemini
 *   ↓
 * 正常總管回答
 *
 * =========================================================
 */
export async function runAiCore(
  input: AiCoreInput,
): Promise<AiCoreResult> {
  const {
    gemini,
    context,
  } = input;

  const model =
    input.model ??
    DEFAULT_MODEL;


  /**
   * =======================================================
   * 建立完整 LINE 情境
   * =======================================================
   */
  const contextPrompt =
    buildAiContextPrompt(
      context,
    );


  /**
   * =======================================================
   * AI 大腦目前收到的完整內容
   * =======================================================
   *
   * 注意：
   *
   * context 是「環境」。
   *
   * coreInstruction 是「身份與思考原則」。
   *
   * 兩者刻意分開。
   */
  const prompt = `
${contextPrompt}

【總管核心身份】

${buildCoreInstruction()}

請理解以上完整情境後，
自然回答目前訊息。

不要只因為目前訊息沒有出現「喳子」、
「總管」或其他固定稱呼，
就認為自己不能回答。

請直接處理目前真正的對話內容。
`.trim();


  /**
   * =======================================================
   * 呼叫 Gemini
   * =======================================================
   */
  const response =
    await gemini.models.generateContent(
      {
        model,

        contents:
          prompt,

        config: {
          systemInstruction:
            SYSTEM_INSTRUCTION,
        },
      },
    );


  /**
   * =======================================================
   * 取得 AI 回覆
   * =======================================================
   */
  const text =
    response.text?.trim() ||
    '奴才一時沒理清思緒，請主上再說一次。';


  return {
    text,
    model,
  };
}