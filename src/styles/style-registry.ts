/**
 * =========================================================
 * Style Registry
 * =========================================================
 *
 * 所有可切換的角色 Style 都在這裡統一註冊。
 *
 * 核心原則：
 *
 * 1. AI 永遠是家庭中的第五個家人。
 * 2. AI 在任何 Style 中都不是最高位角色。
 * 3. 家庭成員才是世界觀中的領導者、高位者與決策者。
 * 4. AI 的角色定位永遠偏向：
 *    - 輔助
 *    - 執行
 *    - 跑腿
 *    - 傳話
 *    - 協助
 *    - 支援
 *
 * =========================================================
 */


export interface StyleDefinition {

  /**
   * =========================================================
   * Style 唯一 ID
   * =========================================================
   */

  id: string;


  /**
   * =========================================================
   * Style 顯示名稱
   * =========================================================
   */

  name: string;


  /**
   * =========================================================
   * Style 說明
   * =========================================================
   */

  description: string;


  /**
   * =========================================================
   * Style 專屬呼叫詞
   * =========================================================
   *
   * 不包含永久通用呼叫詞「阿福」。
   *
   * 通用呼叫詞由：
   *
   * src/call-names.ts
   *
   * 統一管理。
   */

  callNames: readonly string[];


  /**
   * =========================================================
   * 是否允許使用
   * =========================================================
   */

  enabled: boolean;

}


