/**
 * =========================================================
 * 取得所有 Style
 * =========================================================
 */

export function getAllStyles():
  StyleDefinition[] {

  return Object.values(
    STYLE_REGISTRY,
  );

}


/**
 * =========================================================
 * 取得已啟用 Style
 * =========================================================
 */

export function getEnabledStyles():
  StyleDefinition[] {

  return getAllStyles()
    .filter(
      (style) =>
        style.enabled,
    );

}


/**
 * =========================================================
 * 依 ID 取得 Style
 * =========================================================
 */

export function getStyleById(
  styleId: string,
):
  StyleDefinition
  |
  undefined {

  return STYLE_REGISTRY[
    styleId
  ];

}


/**
 * =========================================================
 * 是否為有效且已啟用的 Style
 * =========================================================
 */

export function isEnabledStyle(
  styleId: string,
):
  boolean {

  const style =
    getStyleById(
      styleId,
    );


  return Boolean(
    style?.enabled,
  );

}