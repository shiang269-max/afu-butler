/**
 * =========================================================
 * Style Registry
 * =========================================================
 *
 * 所有可切換的角色 Style 都在這裡統一註冊。
 *
 * 未來：
 *
 * 宮廷
 * 武俠
 * 幫派
 * 西方貴族
 * 軍事
 *
 * 都只需要在這裡新增自己的 Style 定義。
 *
 * 其他系統不應該自己寫死：
 *
 * - Style ID
 * - Style 名稱
 * - Style 專屬呼叫詞
 *
 * =========================================================
 */


export interface StyleDefinition {

  /**
   * =========================================================
   * Style 唯一 ID
   * =========================================================
   *
   * 供：
   *
   * - JSON State
   * - 程式判斷
   * - 未來切換
   *
   * 使用。
   */

  id: string;


  /**
   * =========================================================
   * Style 顯示名稱
   * =========================================================
   */

  name: string;


  /**
   * =========================================================
   * Style 說明
   * =========================================================
   */

  description: string;


  /**
   * =========================================================
   * Style 專屬呼叫詞
   * =========================================================
   *
   * 不包含永久通用呼叫詞「阿福」。
   *
   * 通用呼叫詞由：
   *
   * src/call-names.ts
   *
   * 統一管理。
   *
   * 最終：
   *
   * 通用呼叫詞
   * +
   * 目前 Style 專屬呼叫詞
   *
   * =
   *
   * 目前完整可用呼叫詞。
   */

  callNames: readonly string[];


  /**
   * =========================================================
   * 是否允許使用
   * =========================================================
   *
   * 未來可以先建立 Style，
   * 但尚未正式開放切換。
   */

  enabled: boolean;

}


/**
 * =========================================================
 * 所有 Style Registry
 * =========================================================
 */

export const STYLE_REGISTRY:
  Record<string, StyleDefinition> = {


  /**
   * =========================================================
   * 宮廷 Style
   * =========================================================
   */

  palace: {

    id:
      'palace',

    name:
      '大內總管',

    description:
      '以東方宮廷風格作為語言與表演方式，但本質上仍然是現代家庭中的第五個家人。',

    callNames: [
      '大內總管',
      '總管',
      '內內',
      '喳子',
      '渣子',
    ],

    enabled:
      true,

  },


};


/**
 * =========================================================
 * 取得所有 Style
 * =========================================================
 */

export function getAllStyles(): StyleDefinition[] {

  return Object.values(
    STYLE_REGISTRY,
  );

}


/**
 * =========================================================
 * 取得已啟用 Style
 * =========================================================
 */

export function getEnabledStyles(): StyleDefinition[] {

  return getAllStyles()
    .filter(
      (style) =>
        style.enabled,
    );

}


/**
 * =========================================================
 * 依 ID 取得 Style
 * =========================================================
 */

export function getStyleById(
  styleId: string,
): StyleDefinition | undefined {

  return STYLE_REGISTRY[
    styleId
  ];

}


/**
 * =========================================================
 * 是否為有效且已啟用的 Style
 * =========================================================
 */

export function isEnabledStyle(
  styleId: string,
): boolean {

  const style =
    getStyleById(
      styleId,
    );

  return Boolean(
    style?.enabled,
  );

}