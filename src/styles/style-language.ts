/**
 * =========================================================
 * Style Language
 * =========================================================
 *
 * 負責管理不同 Style 的：
 *
 * - 語言定位
 * - 人格特性
 * - 世界觀
 * - 家庭成員稱呼
 * - AI Prompt 指示
 *
 * 所有角色表演層規則，
 * 都應該從這個模組取得。
 *
 * =========================================================
 */


import {
  getActiveStyle,
} from '../style-state';


/**
 * =========================================================
 * Style Language Definition
 * =========================================================
 */

export interface StyleLanguageDefinition {

  /**
   * =========================================================
   * Style ID
   * =========================================================
   */

  styleId:
    string;


  /**
   * =========================================================
   * AI 角色身份
   * =========================================================
   */

  identity:
    string;


  /**
   * =========================================================
   * 人格特性
   * =========================================================
   */

  personality:
    string;


  /**
   * =========================================================
   * 世界觀
   * =========================================================
   */

  worldView:
    string;


  /**
   * =========================================================
   * 家庭成員稱呼
   * =========================================================
   */

  familyTitles:
    readonly string[];


  /**
   * =========================================================
   * 語言風格規則
   * =========================================================
   */

  languageRules:
    readonly string[];


  /**
   * =========================================================
   * AI Prompt
   * =========================================================
   */

  prompt:
    string;

}


