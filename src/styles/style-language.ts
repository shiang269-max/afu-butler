/**
 * =========================================================
 * Style Language Registry
 * =========================================================
 */

const STYLE_LANGUAGE_REGISTRY:
  Record<
    string,
    StyleLanguageDefinition
  > = {

  palace:
    PALACE_STYLE_LANGUAGE,

  aristocracy:
    ARISTOCRACY_STYLE_LANGUAGE,

  pirate:
    PIRATE_STYLE_LANGUAGE,

  fairy_tale:
    FAIRY_TALE_STYLE_LANGUAGE,

  space_fleet:
    SPACE_FLEET_STYLE_LANGUAGE,

  military_command:
    MILITARY_COMMAND_STYLE_LANGUAGE,

};


/**
 * =========================================================
 * 依 Style ID 取得語言設定
 * =========================================================
 */

export function getStyleLanguage(
  styleId: string,
):
  StyleLanguageDefinition {

  return (
    STYLE_LANGUAGE_REGISTRY[
      styleId
    ]
    ??
    DEFAULT_STYLE_LANGUAGE
  );

}


/**
 * =========================================================
 * 取得目前啟用 Style 的語言設定
 * =========================================================
 */

export function getActiveStyleLanguage():
  StyleLanguageDefinition {

  const style =
    getActiveStyle();


  return getStyleLanguage(
    style.id,
  );

}


/**
 * =========================================================
 * 取得目前 Style AI Prompt
 * =========================================================
 */

export function getActiveStylePrompt():
  string {

  return getActiveStyleLanguage()
    .prompt;

}