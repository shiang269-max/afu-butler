/**
 * =========================================================
 * Style Language
 * =========================================================
 *
 * 負責管理不同 Style 的：
 *
 * - 語言定位
 * - 回覆語氣
 * - AI Prompt 指示
 *
 * 其他功能：
 *
 * - Observer
 * - Vote
 * - Reminder
 * - Function Help
 *
 * 不應該自己寫死特定 Style 的語言規則。
 *
 * 所有角色表演層規則，
 * 都應該從這個模組取得。
 *
 * =========================================================
 */


import {
  getActiveStyle,
} from '../style-state';


/**
 * =========================================================
 * Style Language Definition
 * =========================================================
 */

export interface StyleLanguageDefinition {

  /**
   * =========================================================
   * Style ID
   * =========================================================
   */

  styleId:
    string;


  /**
   * =========================================================
   * AI 角色定位
   * =========================================================
   *
   * 用於讓 AI 理解目前正在扮演的角色。
   */

  identity:
    string;


  /**
   * =========================================================
   * 語言風格規則
   * =========================================================
   *
   * 用於：
   *
   * - AI Prompt
   * - 未來 Style 切換
   */

  languageRules:
    readonly string[];


  /**
   * =========================================================
   * AI Prompt
   * =========================================================
   *
   * 提供完整的 Style Prompt。
   *
   * 這裡只負責「角色表演層」，
   * 不負責功能本身的業務邏輯。
   */

  prompt:
    string;

}


